def fenced(relative: str) -> list[str]:
    text = (LUMEN / relative).read_text(encoding="utf-8")
    language = FENCE_LANGUAGES.get(Path(relative).suffix, "liquid" if "{{" in text or "{%" in text else "text")
    fence = "````" if "```" in text else "```"
    return [f'{fence}{language} title="{relative}"', text.rstrip("\n"), fence, ""]


def lumen_experiments() -> Mapping[str, LoadedExperiment]:
    loaded = load_project(LUMEN).project
    if loaded is None:
        raise SystemExit(f"{LUMEN} does not load: run aqven check {LUMEN}")
    return {str(key): value for key, value in sorted(loaded.experiments.items())}


def factor_of(experiment: LoadedExperiment) -> str:
    factor = experiment.source.spec.varies
    return ticked(factor.what.value) if factor is not None else "none"


def experiment_row(experiment: LoadedExperiment) -> tuple[str, str, str, str]:
    spec = experiment.source.spec
    nodes = ", ".join(ticked(node) for node in spec.varies.nodes) if spec.varies is not None else "—"
    variants = ", ".join(ticked(variant.id) for variant in spec.variants)
    return ticked(experiment.experiment_id), factor_of(experiment), nodes, variants


def experiment_files(experiment: LoadedExperiment) -> list[str]:
    folder = LUMEN / experiment.folder
    files = (
        path.relative_to(LUMEN).as_posix()
        for path in sorted(folder.rglob("*"), key=lambda path: (path.name != EXPERIMENT_FILE, path))
        if path.is_file()
        and path.name != EXPERIMENT_NOTES
        and not SKIPPED_EXPERIMENT_PARTS.intersection(path.relative_to(folder).parts)
    )
    return [line for relative in files for line in fenced(relative)]


def factor_example(kind: FactorKind, experiments: Mapping[str, LoadedExperiment]) -> list[str]:
    experiment = experiments[LUMEN_FACTOR_EXAMPLES[kind]]
    if factor_of(experiment) != ticked(kind.value):
        raise SystemExit(f"{experiment.experiment_id} no longer varies {kind.value}: pick another example")
    return [f"### `{kind.value}`: `{experiment.experiment_id}`", "", *experiment_files(experiment)]


