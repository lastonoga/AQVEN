def front_matter(title: str, description: str, *intro: str) -> list[str]:
    return ["---", f"title: {title}", f"description: {description}", "---", "", GENERATED_NOTE, "", *intro]


def table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    return [
        f"| {' | '.join(header)} |",
        f"| {' | '.join('---' for _ in header)} |",
        *(f"| {' | '.join(row)} |" for row in rows),
        "",
    ]


def ticked(value: object) -> str:
    return f"`{value}`"


def literal_values(alias: TypeAliasType) -> tuple[str, ...]:
    return tuple(str(value) for value in get_args(alias.__value__))


def described[K](members: Iterable[K], meanings: Mapping[K, str]) -> list[tuple[K, str]]:
    missing = [member for member in members if member not in meanings]
    if missing:
        raise SystemExit(f"generate_reference.py has no meaning for {missing}: add one")
    return [(member, meanings[member]) for member in members]


RUN_ERROR_SOURCES: Final[tuple[tuple[str, tuple[str, ...]], ...]] = (
    ("step", tuple(code.value for code in LlmFailureCode)),
    ("model call", tuple(sorted(MODEL_OUTPUT_ERROR_CODES))),
    ("container step: parallel, map, loop", literal_values(ControlErrorCode)),
    ("policy or check function", literal_values(PolicyErrorCode)),
    ("run", tuple(OUTCOME_BY_CODE)),
)
UNLISTED_OUTCOME: Final = OutcomeClass.INFRA_ERROR
CHECK_EFFECTS: Final[Mapping[SkipRule, str]] = {
    run_it: "scored on the output",
    failed_without_output: "binary checks fail, other checks are skipped",
    skip_all: "skipped",
}


def run_error_origins() -> dict[str, str]:
    found: dict[str, str] = {}
    for source, codes in RUN_ERROR_SOURCES:
        found.update({code: source for code in codes if code not in found})
    return found


def outcome_row(code: str, source: str) -> tuple[str, str, str, str]:
    outcome = OUTCOME_BY_CODE.get(code, UNLISTED_OUTCOME)
    return ticked(code), source, ticked(outcome.value), CHECK_EFFECTS[SKIP_RULES[outcome]]


