def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    stale: list[Path] = []
    generated = outputs()
    extra_schemas = set(SCHEMAS.glob("*.json")) - generated.keys()
    if args.check:
        stale.extend(sorted(extra_schemas))
    else:
        for path in extra_schemas:
            path.unlink()
    for path, content in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Generated reference is stale:\n" + "\n".join(str(path) for path in stale))
        return 1
    print("Reference is current" if args.check else "Reference generated")
    return 0


